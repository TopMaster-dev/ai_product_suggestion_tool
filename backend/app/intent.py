# 入力解釈精度の評価（処理ログ用）
# ─────────────────────────────────────────────
def 入力解釈精度評価(ユーザー入力: str, フィルター: dict) -> dict:
    """抽出フィルターの充実度をもとに入力解釈の精度目安を返す"""
    スコア = 40
    理由リスト: list[str] = []

    if フィルター.get("カテゴリ"):
        スコア += 15
        理由リスト.append("カテゴリを特定できました。")
    if フィルター.get("用途"):
        スコア += 15
        理由リスト.append("用途を特定できました。")
    if フィルター.get("季節"):
        スコア += 10
        理由リスト.append("季節条件を特定できました。")

    条件数 = len(フィルター.get("条件リスト", []) or [])
    if 条件数 > 0:
        スコア += min(条件数 * 5, 15)
        理由リスト.append(f"追加条件を{条件数}件抽出できました。")

    キーワード数 = len(フィルター.get("キーワードリスト", []) or [])
    if キーワード数 > 0:
        スコア += 10
        理由リスト.append("検索キーワードを抽出できました。")

    数字件数一致 = re.search(
        r"(\d+)\s*(件|個|つ|点|商品|products?|items?)",
        ユーザー入力,
        flags=re.IGNORECASE,
    )
    if 数字件数一致 and int(数字件数一致.group(1)) == int(フィルター.get("提案件数", 5)):
        スコア += 10
        理由リスト.append("希望件数を正確に反映できました。")

    if len((ユーザー入力 or "").strip()) < 4:
        スコア -= 20
        理由リスト.append("入力文が短いため解釈精度が下がる可能性があります。")

    スコア = max(0, min(100, スコア))
    評価 = "高" if スコア >= 80 else ("中" if スコア >= 60 else "低")

    return {
        "入力解釈精度スコア": スコア,
        "評価": 評価,
        "判定理由": 理由リスト,
    }
