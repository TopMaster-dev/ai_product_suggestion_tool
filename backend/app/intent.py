def フィルター正規化(フィルター: dict, ユーザー入力: str) -> dict:
    """英語入力・表記ゆれを日本語DB向けフィルターに正規化する"""

    英小文字 = (ユーザー入力 or "").lower()
    結果 = dict(フィルター or {})

    # ── カテゴリ補完 ─────────────────────────────
    if not 結果.get("カテゴリ"):
        for 英語, 日本語 in カテゴリ変換表.items():
            if 英語 in 英小文字:
                結果["カテゴリ"] = 日本語
                break
    if not 結果.get("カテゴリ"):
        for 同義語, 正式値 in 日本語同義語カテゴリ.items():
            if 同義語 in ユーザー入力:
                結果["カテゴリ"] = 正式値
                break
    elif 結果.get("カテゴリ"):
        カテゴリ文字列 = str(結果["カテゴリ"]).lower()
        for 英語, 日本語 in カテゴリ変換表.items():
            if 英語 in カテゴリ文字列:
                結果["カテゴリ"] = 日本語
                break

    # ── 用途補完 ─────────────────────────────────
    if not 結果.get("用途"):
        for 英語, 日本語 in 用途変換表.items():
            if 英語 in 英小文字:
                結果["用途"] = 日本語
                break
    if not 結果.get("用途"):
        for 同義語, 正式値 in 日本語同義語用途.items():
            if 同義語 in ユーザー入力:
                結果["用途"] = 正式値
                break

    # ── 季節補完 ─────────────────────────────────
    if not 結果.get("季節"):
        for 英語, 日本語 in 季節変換表.items():
            if 英語 in 英小文字:
                結果["季節"] = 日本語
                break

    # ── 条件リスト補完 ───────────────────────────
    条件リスト = 結果.get("条件リスト") or []
    if not isinstance(条件リスト, list):
        条件リスト = [str(条件リスト)]
    for 英語, 日本語 in 条件変換表.items():
        if 英語 in 英小文字 and 日本語 not in 条件リスト:
            条件リスト.append(日本語)
    for 同義語, 正式値 in 日本語同義語条件.items():
        if 同義語 in ユーザー入力 and 正式値 not in 条件リスト:
            条件リスト.append(正式値)
    結果["条件リスト"] = 条件リスト

    # ── 並び順意図 ───────────────────────────────
    並び順 = []
    if any(k in ユーザー入力 for k in ["売れ筋", "人気"]):
        並び順.append("売れ筋優先")
    if any(k in ユーザー入力 for k in ["在庫", "すぐ出せる", "即納"]):
        並び順.append("在庫優先")
    if not 並び順:
        並び順 = ["売れ筋優先", "在庫優先"]
    結果["並び順"] = 並び順

    # ── 提案件数（AI推定） ───────────────────────
    try:
        if 結果.get("提案件数") is None:
            raise ValueError()
        結果["提案件数"] = int(結果["提案件数"])
    except (ValueError, TypeError):
        結果["提案件数"] = 設定.DEFAULT_SUGGESTION_COUNT

    # ── ユーザー入力から件数を最優先で抽出 ──────
    要求件数 = ユーザー指定件数抽出(ユーザー入力)
    if 要求件数 is not None:
        結果["提案件数"] = 要求件数

    # ── キーワード補完 ───────────────────────────
    キーワードリスト = 結果.get("キーワードリスト") or []
    if not isinstance(キーワードリスト, list):
        キーワードリスト = [str(キーワードリスト)]

    # 文っぽいキーワード（助詞を含む or 30文字超）を除外する
    def _は文か(値: str) -> bool:
        if len(値) > 30:
            return True
        if any(助詞 in 値 for 助詞 in 文判定助詞):
            return True
        return False

    キーワードリスト = [k for k in キーワードリスト if k and not _は文か(str(k))]

    # 入力本文から既知の商品種別を抜き出して追加（AIが拾いきれない場合の保険）
    for 種別 in 日本語商品種別一覧:
        if 種別 in ユーザー入力 and 種別 not in キーワードリスト:
            キーワードリスト.append(種別)
            # カテゴリが未設定なら、これを暫定カテゴリにする
            if not 結果.get("カテゴリ"):
                結果["カテゴリ"] = 種別

    # カタカナ語（コーヒー・ティーアイテム 等）も自動でキーワード化する
    for 一致 in _カタカナ語.findall(ユーザー入力 or ""):
        値 = 一致.strip("・ー")
        if not 値 or len(値) < 2:
            continue
        # 単独の「アイテム／グッズ／セット」等は汎用語なのでスキップ
        if 値 in {"アイテム", "グッズ", "セット", "シリーズ", "タイプ", "サイズ"}:
            continue
        if 値 not in キーワードリスト:
            キーワードリスト.append(値)
            if not 結果.get("カテゴリ"):
                結果["カテゴリ"] = 値

    for 値 in (結果.get("カテゴリ"), 結果.get("用途"), 結果.get("季節")):
        if 値 and 値 not in キーワードリスト:
            キーワードリスト.append(値)

    結果["キーワードリスト"] = キーワードリスト[:6]

    # ── 範囲ガード ───────────────────────────────
    結果["提案件数"] = max(
        1,
        min(int(結果.get("提案件数", 設定.DEFAULT_SUGGESTION_COUNT)), 設定.MAX_SUGGESTION_COUNT),
    )
    return 結果


def ユーザー指定件数抽出(ユーザー入力: str) -> Optional[int]:
    """ユーザー入力から明示件数(1-30)を抽出する"""
    if not ユーザー入力:
        return None

    英小文字 = ユーザー入力.lower()

    # まずは件数単位（件・個・つ・点・商品 等）を伴う数字を最優先で探す。
    # 価格表現（"1000円以下"）と件数表現（"5点"）が同居しても誤検出しないようにする。
    件数単位付き = re.findall(
        r"(\d+)\s*(?:件|個|つ|点|商品|products?|items?)",
        ユーザー入力,
        flags=re.IGNORECASE,
    )
    if 件数単位付き:
        値 = int(件数単位付き[-1])  # 末尾優先：「予算1000円で5点」を 5 と解釈する
        return max(1, min(設定.MAX_SUGGESTION_COUNT, 値))

    漢数字一致 = re.search(r"(一|二|三|四|五|六|七|八|九|十)\s*(件|個|つ|点|商品)?", ユーザー入力)
    if 漢数字一致:
        return 件数漢数字表.get(漢数字一致.group(1))

    for 単語, 値 in 件数英単語表.items():
        if re.search(rf"\b{単語}\b", 英小文字):
            return 値

    # 単位なし数字は誤検出しやすい（金額・型番・容量など）ので拾わない。
    return None


