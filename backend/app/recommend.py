# ─────────────────────────────────────────────
# HTML除去ユーティリティ
#   ks_m_items.商品説明 等には <br>, <img>, <div>, <b>, <hr> 等の HTML が
#   そのまま入っているケースが多い。AI に渡す前にプレーンテキスト化する。
# ─────────────────────────────────────────────
_HTML_BR = re.compile(r"<\s*br\s*/?>", re.IGNORECASE)
_HTML_BLOCK_END = re.compile(
    r"</?\s*(p|div|tr|li|hr|h[1-6]|ul|ol|table)\b[^>]*>",
    re.IGNORECASE,
)
_HTML_SCRIPT_OR_STYLE = re.compile(
    r"<\s*(script|style)\b[^>]*>.*?<\s*/\s*\1\s*>",
    re.IGNORECASE | re.DOTALL,
)
_HTML_IMG_TAG = re.compile(r"<\s*img\b[^>]*>", re.IGNORECASE)
_HTML_OTHER_TAG = re.compile(r"<[^>]+>")
_余分空白 = re.compile(r"[ \t\u3000]+")
_余分改行 = re.compile(r"\n\s*\n+")


def HTML除去(値: str) -> str:
    """文字列内の HTML タグ／エンティティを除去してプレーンテキスト化する"""
    if not 値:
        return 値
    if "<" not in 値 and "&" not in 値:
        return 値

    # script/style ブロックは中身ごと削除
    結果 = _HTML_SCRIPT_OR_STYLE.sub("", 値)

    # img タグは「[画像]」プレースホルダに置換
    結果 = _HTML_IMG_TAG.sub("", 結果)

    # 改行を意味するタグを \n に
    結果 = _HTML_BR.sub("\n", 結果)
    結果 = _HTML_BLOCK_END.sub("\n", 結果)

    # 残りの全タグを除去
    結果 = _HTML_OTHER_TAG.sub("", 結果)

    # HTMLエンティティをデコード（&amp; → & など）
    結果 = html.unescape(結果)

    # 連続空白／改行を整える
    結果 = _余分空白.sub(" ", 結果)
    結果 = _余分改行.sub("\n\n", 結果)

    return 結果.strip()


# ─────────────────────────────────────────────
# 値整形ヘルパー
# ─────────────────────────────────────────────
def _安全に文字列化(値: Any) -> str:
    """Decimal / datetime / None / HTML混じり文字列 を読みやすいプレーンテキストにする"""
    if 値 is None:
        return "—"
    if isinstance(値, Decimal):
        return f"{値:,.2f}".rstrip("0").rstrip(".") or "0"
    if isinstance(値, (datetime, date)):
        return 値.strftime("%Y-%m-%d")
    if isinstance(値, str):
        整形済み = HTML除去(値).strip()
        return 整形済み or "—"
    return str(値)


def 全カラム整形(全項目: dict) -> str:
    """ks_m_items の1行を「グループ→項目→値」の見やすい日本語に整形する"""
    if not 全項目:
        return ""

    行一覧: List[str] = []
    使用済み: set[str] = set()

    for グループ名, 列名一覧 in columns.詳細表示グループ一覧:
        グループ行: List[str] = []
        for 列名 in 列名一覧:
            if 列名 not in 全項目:
                continue
            使用済み.add(列名)
            値 = _安全に文字列化(全項目.get(列名))
            if 値 != "—":
                グループ行.append(f"  - {列名}: {値}")
        if グループ行:
            行一覧.append(f"■ {グループ名}")
            行一覧.extend(グループ行)
            行一覧.append("")

    # グループ未指定のカラムを「その他」にまとめる
    残り = [c for c in 全項目.keys() if c not in 使用済み]
    if 残り:
        その他 = [f"  - {c}: {_安全に文字列化(全項目.get(c))}" for c in 残り
                 if _安全に文字列化(全項目.get(c)) != "—"]
        if その他:
            行一覧.append("■ その他")
            行一覧.extend(その他)

    return "\n".join(行一覧).strip()


# ─────────────────────────────────────────────
# 商品リストの推薦文生成
# ─────────────────────────────────────────────
def 推薦文生成(ユーザー入力: str, 商品リスト: Iterable[dict], _フィルター: dict) -> str:
    """検索ヒットした複数商品をまとめて紹介する日本語文を生成する"""

    商品リスト = list(商品リスト)
    if not 商品リスト:
        return (
            "申し訳ございません。ご入力の条件に合う商品が現在のデータベースに見つかりませんでした。\n\n"
            "以下をお試しください：\n"
            "・条件を少し変えて再度検索する\n"
            "・カテゴリや用途のみで検索する\n"
            "・在庫状況を後日ご確認いただく"
        )

    def _整形(値: Any, 既定: str = "なし") -> str:
        テキスト = HTML除去(str(値)) if 値 not in (None, "") else 既定
        return テキスト or 既定

    商品テキスト一覧: List[str] = []
    for 番号, 商品 in enumerate(商品リスト, 1):
        商品テキスト一覧.append(
            f"""
【商品{番号}】
商品コード：{商品.get('商品コード', '不明')}
JANコード：{商品.get('JANコード', '不明')}
商品名：{_整形(商品.get('商品名'), '不明')}
メーカー：{_整形(商品.get('メーカー名'), '不明')}
カテゴリ：{_整形(商品.get('カテゴリ'), '不明')} / {_整形(商品.get('サブカテゴリ'), '')}
売価(税込)：¥{float(商品.get('卸価格_税抜', 0)):,.0f}
定価：¥{float(商品.get('定価_税抜', 0)):,.0f}
入数：{商品.get('入数', '不明')}
商品特徴：{_整形(商品.get('商品特徴'))}
商品説明：{_整形(商品.get('商品説明'))}
在庫数：{商品.get('在庫数', '不明')}点
タグ：{_整形(商品.get('タグ'))}
""".strip()
        )

    プロンプト = f"""
あなたは商品提案の専門アシスタントです。
以下のユーザーの要望と商品情報をもとに、自然で丁寧な日本語で商品を紹介してください。

【ユーザーの要望】
{ユーザー入力}

【提案商品データ（データベースより取得）】
{chr(10).join(商品テキスト一覧)}

【回答のルール】
- 商品ごとに「商品名」「主要データ（箇条書き）」「商品説明」「おすすめ理由」を分けて書く
- データベースに含まれる項目は省略せず明記する
- データベースに記載されていない情報は絶対に作り上げない
- 不明な点は「データにございません」と正直に答える
- 丁寧な日本語で、最後に「他にご質問やご要望がございましたら、お気軽にどうぞ。」と添える
- HTML タグや Markdown の画像構文（<br>, <img>, <b>, ![](...) など）を絶対に出力しない。プレーンテキストの日本語のみで回答する
"""

    try:
        生応答 = チャット補完(プロンプト, 最大トークン=1500, 温度=0.4)
        return HTML除去(生応答)
    except OpenAIエラー:
        # OpenAI失敗時はテンプレ文でフォールバック
        上位 = 商品リスト[:3]
        行 = [
            f"・{HTML除去(str(p['商品名']))}（{p['カテゴリ']}）- 売価 ¥{float(p['卸価格_税抜']):,.0f}、在庫 {p['在庫数']}点"
            for p in 上位
        ]
        return (
            "以下の商品が条件に合致しました。\n\n"
            + "\n".join(行)
            + "\n\n他にご質問やご要望がございましたら、お気軽にどうぞ。"
        )


# ─────────────────────────────────────────────
# 単一商品の詳細説明（DB全カラムを反映）
# ─────────────────────────────────────────────
def 商品単体説明生成(ユーザー入力: str, 全項目: dict, 使用フィルター: dict) -> str:
    """選択商品の全カラムをAIに渡し、日本語の詳細説明を生成する"""
    if not 全項目:
        return "ご指定の商品が見つかりませんでした。"

    詳細テキスト = 全カラム整形(全項目)

    フィルターJSON = json.dumps(使用フィルター or dict(), ensure_ascii=False)

    プロンプト = f"""
あなたは商品提案の専門アシスタントです。
以下の情報をもとに、選択された1商品について「詳細データ」「商品説明」「おすすめ理由」に分けて日本語で説明してください。

【ユーザー入力】
{ユーザー入力 or "（指定なし）"}

【使用フィルター】
{フィルターJSON}

【選択商品データ（DB全カラム）】
{詳細テキスト}

【出力ルール】
- 上記DBデータに含まれる項目はすべて読者に分かりやすく紹介する（値が空の項目は省略してよい）
- 「商品の詳細データ」「商品説明」「おすすめ理由」「ご提案コメント」の見出し構成にする
- DBにない情報は絶対に作らない。不明値は「データにございません」と書く
- 日本円表示は「¥1,234」形式で揃える
- HTML タグ（<br>, <img>, <b>, <div>, <hr> など）や HTML エンティティ、Markdown の画像構文を絶対に出力しない。プレーンテキストの日本語のみで書く
- 商品説明本文に画像参照や装飾タグが含まれていても、テキスト部分だけを抽出して使う
"""

    try:
        生応答 = チャット補完(プロンプト, 最大トークン=1200, 温度=0.4)
        return HTML除去(生応答)
    except OpenAIエラー:
        return (
            "【商品の詳細データ】\n"
            + 詳細テキスト
            + "\n\n【ご提案コメント】\n"
            + "AI生成は一時的に利用できないため、データベースから取得した詳細のみを表示しています。"
        )
