"""
/api/チャット ：ユーザー入力 → 意図抽出 → DB検索 → 推薦文生成。

旧 main.py のメインエンドポイントを忠実に再現したルーター実装。
"""

from __future__ import annotations

import json
from typing import Any, Dict, List

import mysql.connector
from fastapi import APIRouter

from ..intent import 意図抽出, フィルター正規化, 入力解釈精度評価, ユーザー指定件数抽出
from ..models import チャットリクエスト, チャットレスポンス
from ..recommend import 推薦文生成
from ..search import 商品検索
from ..serialization import 行リストを安全化

ルーター = APIRouter(tags=["チャット"])


@ルーター.post("/api/チャット", response_model=チャットレスポンス, summary="商品提案チャット")
async def チャット(リクエスト: チャットリクエスト) -> チャットレスポンス:
    """日本語の問い合わせを受け取り、最適な商品を提案する"""

    処理ログ: List[Dict[str, Any]] = []

    try:
        # ── ステップ① ＆ ② ：意図抽出 ──
        処理ログ.append({"ステップ": 1, "処理名": "自然言語解析・意図抽出", "状態": "処理中"})
        フィルター = 意図抽出(リクエスト.メッセージ)
        フィルター = フィルター正規化(フィルター, リクエスト.メッセージ)

        明示件数 = ユーザー指定件数抽出(リクエスト.メッセージ)
        if 明示件数 is not None:
            フィルター["提案件数"] = 明示件数

        処理ログ[0].update({
            "状態": "完了",
            "抽出結果": フィルター,
            "入力精度": 入力解釈精度評価(リクエスト.メッセージ, フィルター),
        })

        # ── ステップ③ ：DB検索 ──
        処理ログ.append({"ステップ": 2, "処理名": "データベース検索・フィルタリング", "状態": "処理中"})
        商品リスト = 商品検索(フィルター)

        最終件数 = max(1, min(int(フィルター.get("提案件数") or 5), 30))
        商品リスト = 商品リスト[:最終件数]

        処理ログ[1].update({
            "状態": "完了",
            "件数": f"{len(商品リスト)}件の商品が見つかりました",
        })

        # ── ステップ④ ：推薦文生成 ──
        処理ログ.append({"ステップ": 3, "処理名": "AI推薦文・おすすめ理由生成", "状態": "処理中"})
        回答 = 推薦文生成(リクエスト.メッセージ, 商品リスト, フィルター)
        処理ログ[2]["状態"] = "完了"

        return チャットレスポンス(
            回答=回答,
            提案商品リスト=行リストを安全化(商品リスト),
            使用フィルター=フィルター,
            処理ステップログ=処理ログ,
        )

    except json.JSONDecodeError:
        処理ログ.append({"ステップ": 99, "処理名": "エラーハンドリング", "状態": "エラー"})
        return チャットレスポンス(
            回答="意図抽出の形式解析でエラーが発生しました。別の表現でお試しください。",
            提案商品リスト=[],
            使用フィルター={},
            処理ステップログ=処理ログ,
        )
    except mysql.connector.Error as エラー:
        処理ログ.append({"ステップ": 99, "処理名": "エラーハンドリング", "状態": "エラー"})
        return チャットレスポンス(
            回答=f"データベース接続または検索でエラーが発生しました: {エラー}",
            提案商品リスト=[],
            使用フィルター={},
            処理ステップログ=処理ログ,
        )
    except Exception as エラー:  # noqa: BLE001
        処理ログ.append({"ステップ": 99, "処理名": "エラーハンドリング", "状態": "エラー"})
        return チャットレスポンス(
            回答=f"内部処理でエラーが発生しました: {エラー}",
            提案商品リスト=[],
            使用フィルター={},
            処理ステップログ=処理ログ,
        )
